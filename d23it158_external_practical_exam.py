def fgsm_attack(image, epsilon, data_grad):
    # Collect the sign of the gradients
    sign_data_grad = data_grad.sign()
    # Create the perturbed image by adjusting each pixel of the input image
    perturbed_image = image + epsilon * sign_data_grad
    # Adding clipping to maintain [0,1] range
    perturbed_image = torch.clamp(perturbed_image, 0, 1)
    return perturbed_image

def pgd_attack(model, image, target, epsilon, alpha, num_iter=10):
    # L-infinity PGD attack with random start
    perturbed_image = image.clone().detach()
    # Random start
    perturbed_image = perturbed_image + torch.empty_like(perturbed_image).uniform_(-epsilon, epsilon)
    perturbed_image = torch.clamp(perturbed_image, 0, 1).detach()

    for _ in range(num_iter):
        perturbed_image.requires_grad = True
        output = model(perturbed_image)
        loss = criterion(output, target)
        model.zero_grad()
        loss.backward()

        # Update step
        data_grad = perturbed_image.grad.data
        perturbed_image = perturbed_image.detach() + alpha * data_grad.sign()
        # Projection step (L-infinity box constraint around original image)
        eta = torch.clamp(perturbed_image - image, min=-epsilon, max=epsilon)
        perturbed_image = torch.clamp(image + eta, min=0, max=1).detach()

    return perturbed_image

def evaluate_attack(model, loader, attack_type, epsilon, alpha=None):
    model.eval()
    correct = 0
    total = 0
    for data, target in loader:
        data, target = data.to(device), target.to(device)
        if epsilon == 0:
            outputs = model(data)
            _, predicted = torch.max(outputs.data, 1)
            correct += (predicted == target).sum().item()
            total += target.size(0)
            continue

        if attack_type == 'fgsm':
            data.requires_grad = True
            outputs = model(data)
            loss = criterion(outputs, target)
            model.zero_grad()
            loss.backward()
            data_grad = data.grad.data
            perturbed_data = fgsm_attack(data, epsilon, data_grad)
        elif attack_type == 'pgd':
            perturbed_data = pgd_attack(model, data, target, epsilon, alpha)

        outputs = model(perturbed_data)
        _, predicted = torch.max(outputs.data, 1)
        correct += (predicted == target).sum().item()
        total += target.size(0)

    return 100 * correct / total

