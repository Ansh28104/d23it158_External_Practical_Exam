def get_visualizations(model, loader, epsilon=0.20):
    model.eval()
    clean_images = []
    adv_images = []
    clean_preds = []
    adv_preds = []
    true_labels = []

    for data, target in loader:
        data, target = data.to(device), target.to(device)
        data.requires_grad = True
        outputs = model(data)
        loss = criterion(outputs, target)
        model.zero_grad()
        loss.backward()
        data_grad = data.grad.data
        perturbed_data = fgsm_attack(data, epsilon, data_grad)

        adv_outputs = model(perturbed_data)
        _, preds = torch.max(outputs.data, 1)
        _, adv_preds_batch = torch.max(adv_outputs.data, 1)

        # Identify misclassified index sequences
        for i in range(len(target)):
            if preds[i] == target[i] and adv_preds_batch[i] != target[i]:
                clean_images.append(data[i].detach().cpu().squeeze().numpy())
                adv_images.append(perturbed_data[i].detach().cpu().squeeze().numpy())
                clean_preds.append(preds[i].item())
                adv_preds.append(adv_preds_batch[i].item())
                true_labels.append(target[i].item())
                if len(clean_images) >= 5:
                    return clean_images, adv_images, clean_preds, adv_preds, true_labels

